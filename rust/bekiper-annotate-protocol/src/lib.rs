//! Protocol primitives shared by native and browser annotation transports.
//!
//! The full native message graph remains in `bekiper-annotate::server::wire`
//! because it contains server-only domain types. This crate owns the bytes
//! that every transport must agree on: protocol version, request envelope,
//! and the length-prefixed bincode frame.

use serde::{Deserialize, Serialize};

/// Explicit virtual center-zone convention. Image edges never select a rule.
/// Physical values are metres; video-relative fractions are dimensionless.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "method", rename_all = "snake_case", deny_unknown_fields)]
pub enum ArenaCenterRule {
    Manual {},
    Dimensions {
        width_meters: f64,
        height_meters: f64,
    },
    WallInset {
        inset_meters: f64,
    },
    /// Centered rectangle sized relative to the video-derived arena floor.
    /// Omitted fractions are resolved by the detector's canonical defaults.
    VideoRelative {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        width_fraction: Option<f64>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        height_fraction: Option<f64>,
    },
    /// Arena and center rectangles of fixed physical size, generated by the
    /// pipeline; no outline needs to be drawn or reviewed. With `detect_box`
    /// the arena is each video's detected box, which also defines that video's
    /// scale and centers the zone; otherwise (or when no box is found) both are
    /// centered on the video's own frame center with the recording's scale.
    FrameCentered {
        arena_width_meters: f64,
        arena_height_meters: f64,
        center_width_meters: f64,
        center_height_meters: f64,
        #[serde(default)]
        detect_box: bool,
    },
}

impl Default for ArenaCenterRule {
    fn default() -> Self {
        Self::Manual {}
    }
}

/// The recording actually displayed by an editor. Mutations must carry all
/// three fields so reassigning a recording cannot apply an old editor's save.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecordingPrecondition {
    pub recording_id: String,
    pub video_sha256: String,
    pub binding_revision: i64,
}

pub mod sync {
    use super::{MutationId, Revision};
    use serde::{Deserialize, Serialize};

    #[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
    pub struct DocumentId {
        pub collection: String,
        pub key: String,
    }
    impl DocumentId {
        pub fn new(collection: impl Into<String>, key: impl Into<String>) -> Self {
            Self {
                collection: collection.into(),
                key: key.into(),
            }
        }
    }
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
    pub enum MutationKind {
        Annotation,
        Review,
        Group,
        Deletion,
    }
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub struct DocumentBase {
        pub document: DocumentId,
        pub base_revision: Option<Revision>,
    }
    /// Retries carry the same ID and a hash of the complete operation.
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub struct MutationRequest {
        pub mutation_id: MutationId,
        pub actor: String,
        pub dataset: String,
        pub kind: MutationKind,
        pub bases: Vec<DocumentBase>,
        pub payload_hash: String,
    }
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub struct MutationResult {
        pub mutation_id: MutationId,
        pub applied: bool,
        pub conflict: bool,
        pub cursor: Revision,
        pub document_revisions: Vec<(DocumentId, Revision)>,
        pub last_modified: i64,
    }
    #[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
    pub struct DeletionMarker {
        pub document: DocumentId,
        pub deleted_by: String,
        pub cursor: Revision,
    }
    pub fn is_stale(base: Option<Revision>, current: Option<Revision>) -> bool {
        base != current
    }
}

/// Wire protocol version negotiated by native and browser clients.
///
/// Version 5 adds explicit capability, revision, cursor, and mutation receipt
/// data types. The message enums remain server-owned for now, but every client
/// can use these values to make reconnect and conflict handling deterministic.
pub const PROTOCOL_VERSION: u32 = 5;

/// Maximum size accepted for a bulk frame stream.
pub const MAX_BULK_FRAME_BYTES: usize = 128 * 1024 * 1024;

/// Maximum size accepted for a length-prefixed control-stream message.
pub const MAX_CONTROL_MESSAGE_BYTES: usize = 4 * 1024 * 1024;

/// Correlation identifier echoed by the server in response envelopes.
pub type RequestId = u64;

/// Monotonic server revision for a dataset/session event stream.
pub type Revision = u64;

/// Opaque client-generated id used to make retries idempotent.
pub type MutationId = u128;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Capability {
    pub name: String,
    #[serde(default)]
    pub version: u32,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct EventCursor {
    pub revision: Revision,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct RevisionSet {
    pub base: Revision,
    pub current: Revision,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct TransportLimits {
    pub max_control_message_bytes: u32,
    pub max_bulk_frame_bytes: u32,
    pub max_in_flight_requests: u16,
}

impl Default for TransportLimits {
    fn default() -> Self {
        Self {
            max_control_message_bytes: MAX_CONTROL_MESSAGE_BYTES as u32,
            max_bulk_frame_bytes: MAX_BULK_FRAME_BYTES as u32,
            max_in_flight_requests: 64,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Welcome {
    pub protocol_version: u32,
    pub dataset_id: String,
    #[serde(default)]
    pub capabilities: Vec<Capability>,
    #[serde(default)]
    pub cursor: EventCursor,
    #[serde(default)]
    pub limits: TransportLimits,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MutationReceipt {
    pub mutation_id: MutationId,
    pub revision: Revision,
    pub base_revision: Revision,
    pub applied: bool,
    #[serde(default)]
    pub conflict: bool,
}

/// Error raised when a length-prefixed frame exceeds the negotiated budget.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FrameError {
    TooLarge { len: usize, max: usize },
}

impl std::fmt::Display for FrameError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::TooLarge { len, max } => write!(f, "frame too large: {len} bytes (max {max})"),
        }
    }
}

impl std::error::Error for FrameError {}

/// Request/response envelope used on the bidirectional control stream.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Envelope<T> {
    #[serde(default)]
    pub request_id: Option<RequestId>,
    pub payload: T,
}

impl<T> Envelope<T> {
    pub fn request(request_id: RequestId, payload: T) -> Self {
        Self {
            request_id: Some(request_id),
            payload,
        }
    }

    pub fn push(payload: T) -> Self {
        Self {
            request_id: None,
            payload,
        }
    }
}

/// Prefix a bincode body with the protocol's four-byte big-endian length.
pub fn frame_bytes(body: &[u8]) -> Vec<u8> {
    let mut framed = Vec::with_capacity(4 + body.len());
    framed.extend_from_slice(&(body.len() as u32).to_be_bytes());
    framed.extend_from_slice(body);
    framed
}

/// Return the body of a complete length-prefixed frame, if available.
pub fn deframe_with_limit(bytes: &[u8], max_bytes: usize) -> Option<Result<&[u8], FrameError>> {
    if bytes.len() < 4 {
        return None;
    }
    let len = u32::from_be_bytes(bytes[..4].try_into().expect("length prefix")) as usize;
    if len > max_bytes {
        return Some(Err(FrameError::TooLarge {
            len,
            max: max_bytes,
        }));
    }
    if bytes.len() < 4 + len {
        return None;
    }
    Some(Ok(&bytes[4..4 + len]))
}

/// Deframe a bulk message using the protocol's largest accepted budget.
pub fn deframe(bytes: &[u8]) -> Option<Result<&[u8], FrameError>> {
    deframe_with_limit(bytes, MAX_BULK_FRAME_BYTES)
}

/// Encode and frame a serde value using the native bincode configuration.
pub fn encode_frame<T: Serialize>(value: &T) -> Result<Vec<u8>, bincode::error::EncodeError> {
    Ok(frame_bytes(&bincode::serde::encode_to_vec(
        value,
        bincode::config::standard(),
    )?))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frame_prefix_is_native_compatible() {
        assert_eq!(frame_bytes(b"abc"), vec![0, 0, 0, 3, b'a', b'b', b'c']);
    }

    #[test]
    fn envelope_round_trips_with_standard_bincode() {
        let original = Envelope::request(7, String::from("frame"));
        let framed = encode_frame(&original).unwrap();
        let len = u32::from_be_bytes(framed[..4].try_into().unwrap()) as usize;
        let (decoded, read): (Envelope<String>, usize) =
            bincode::serde::decode_from_slice(&framed[4..4 + len], bincode::config::standard())
                .unwrap();
        assert_eq!(read, len);
        assert_eq!(decoded, original);
    }

    #[test]
    fn control_and_bulk_budgets_match_native_protocol() {
        assert_eq!(MAX_CONTROL_MESSAGE_BYTES, 4 * 1024 * 1024);
        assert_eq!(MAX_BULK_FRAME_BYTES, 128 * 1024 * 1024);
        const {
            assert!(MAX_CONTROL_MESSAGE_BYTES < MAX_BULK_FRAME_BYTES);
        }
    }

    #[test]
    fn deframe_respects_custom_limit() {
        let framed = frame_bytes(b"abc");
        assert_eq!(deframe_with_limit(&framed, 3).unwrap().unwrap(), b"abc");
        assert_eq!(
            deframe_with_limit(&framed, 2),
            Some(Err(FrameError::TooLarge { len: 3, max: 2 }))
        );
        assert!(deframe_with_limit(&framed[..5], 3).is_none());
    }

    #[test]
    fn v5_handshake_metadata_round_trips() {
        let welcome = Welcome {
            protocol_version: PROTOCOL_VERSION,
            dataset_id: "neo-imen".into(),
            capabilities: vec![Capability {
                name: "frame.av1".into(),
                version: 1,
            }],
            cursor: EventCursor { revision: 42 },
            limits: TransportLimits::default(),
        };
        let encoded = bincode::serde::encode_to_vec(&welcome, bincode::config::standard()).unwrap();
        let (decoded, _): (Welcome, usize) =
            bincode::serde::decode_from_slice(&encoded, bincode::config::standard()).unwrap();
        assert_eq!(decoded, welcome);
    }

    #[test]
    fn mutation_receipt_distinguishes_conflicts() {
        let receipt = MutationReceipt {
            mutation_id: 9,
            revision: 8,
            base_revision: 7,
            applied: false,
            conflict: true,
        };
        assert!(receipt.conflict);
        assert!(!receipt.applied);
    }
}
